'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { useTranslation } from '@/i18n/context';

const navItems = [
  { key: 'home', path: '/', icon: HomeIcon },
  { key: 'log', path: '/log', icon: PlusIcon },
  { key: 'history', path: '/history', icon: ClockIcon },
  { key: 'settings', path: '/settings', icon: GearIcon },
] as const;

export default function Navigation() {
  const pathname = usePathname();
  const { t } = useTranslation();

  if (pathname === '/setup') return null;

  return (
    <nav className="fixed bottom-0 left-0 right-0 bg-white border-t border-gray-200 z-50">
      <div className="flex justify-around max-w-2xl mx-auto pb-[env(safe-area-inset-bottom,8px)]">
        {navItems.map(({ key, path, icon: Icon }) => {
          const active = pathname === path;
          return (
            <Link
              key={key}
              href={path}
              className={`flex flex-col items-center pt-3 pb-2 px-3 min-w-[64px] transition-colors ${
                active ? 'text-blue-600' : 'text-gray-400 hover:text-gray-600'
              }`}
            >
              <Icon className="w-6 h-6" />
              <span className="text-xs mt-1">{t(`nav.${key}`)}</span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

